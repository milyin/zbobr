/// Merge two named prompt-slot maps using per-key `TomlOption` semantics.
///
/// Overlay's key wins unless it is `Absent`. `ExplicitNone` (nan) clears the slot.
fn merge_prompt_maps(
    base: Option<IndexMap<String, TomlOption<PathBuf>>>,
    overlay: Option<IndexMap<String, TomlOption<PathBuf>>>,
) -> Option<IndexMap<String, TomlOption<PathBuf>>> {
    match (base, overlay) {
        (Some(mut base_map), Some(over_map)) => {
            for (k, v) in over_map {
                if let Some(base_v) = base_map.get_mut(&k) {
                    *base_v = base_v.clone().merge(v);
                } else {
                    base_map.insert(k, v);
                }
            }
            Some(base_map)
        }
        (None, over) => over,
        (base, None) => base,
    }
}

/// Auto-generated by #[config_struct] for every config struct.
pub trait Config: Sized {
    type Toml: Default + for<'de> serde::Deserialize<'de>;
    type Args: clap::Args + zbobr_utility::PrefixedArgs + Default + Clone;
    fn build(toml: Option<Self::Toml>, args: Self::Args, config_dir: &Path) -> Self;
}

/// Definition of a role: which MCP tools it can access, named prompt files, and optional tool override.
///
/// `mcp = None` means the field was absent in the config (inherit from base during merging,
/// or no tools at runtime). `mcp = Some(vec![])` explicitly allows no tools.
#[derive(Clone, Debug, serde::Deserialize, serde::Serialize, Default)]
#[serde(deny_unknown_fields)]
pub struct RoleDefinition {
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub mcp: Option<Vec<McpTool>>,
    /// Named prompt slots for this role. Each key is a slot name (e.g. "main"),
    /// value is the path to the prompt file (`nan` clears an inherited slot).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub prompts: Option<IndexMap<String, TomlOption<PathBuf>>>,
    /// Tool name override for this role. Overrides the global dispatcher `tool`.
    /// Stage-level `tool` takes precedence over this.
    #[serde(default, skip_serializing_if = "TomlOption::is_absent")]
    pub tool: TomlOption<Tool>,
}

impl RoleDefinition {
    /// Resolve relative path fields against the given base directory.
    pub fn resolve_paths(self, config_dir: &Path) -> Self {
        Self {
            prompts: self.prompts.map(|map| {
                map.into_iter()
                    .map(|(k, v)| (k, v.map(|p| zbobr_utility::resolve_path(p, config_dir))))
                    .collect()
            }),
            ..self
        }
    }
}

impl zbobr_utility::ResolvePathValue for RoleDefinition {
    fn resolve_path_value(self, base: &Path) -> Self {
        self.resolve_paths(base)
    }
}

impl zbobr_utility::MergeToml for RoleDefinition {
    fn merge_toml(self, other: Self) -> Self {
        Self {
            mcp: other.mcp.or(self.mcp),
            prompts: merge_prompt_maps(self.prompts, other.prompts),
            tool: self.tool.merge(other.tool),
        }
    }
}

/// A provider definition: a named executor configuration with optional inheritance.
#[derive(Clone, Debug, serde::Deserialize, serde::Serialize)]
#[serde(deny_unknown_fields)]
pub struct ProviderDefinition {
    /// Executor type (e.g. "claude", "copilot", "mcp-tester").
    /// Required unless `parent` is set.
    #[serde(default, skip_serializing_if = "TomlOption::is_absent")]
    pub executor: TomlOption<Executor>,
    /// Parent provider to inherit settings from. Child fields override parent.
    #[serde(default, skip_serializing_if = "TomlOption::is_absent")]
    pub parent: TomlOption<Provider>,
    /// Selection priority. Higher values are preferred. Omit to inherit from
    /// parent (root providers default to 10).
    #[serde(default, skip_serializing_if = "TomlOption::is_absent")]
    pub priority: TomlOption<i32>,
    /// Enable plan mode for this provider. Overrides any executor default.
    #[serde(default, skip_serializing_if = "TomlOption::is_absent")]
    pub plan_mode: TomlOption<bool>,
    /// API key for the executor (e.g. Anthropic API key for the claude executor).
    #[serde(default, skip_serializing_if = "TomlOption::is_absent")]
    pub access_key: TomlOption<Secret>,
}

impl zbobr_utility::MergeToml for ProviderDefinition {
    fn merge_toml(self, other: Self) -> Self {
        Self {
            executor: self.executor.merge(other.executor),
            parent: self.parent.merge(other.parent),
            priority: self.priority.merge(other.priority),
            plan_mode: self.plan_mode.merge(other.plan_mode),
            access_key: self.access_key.merge(other.access_key),
        }
    }
}

