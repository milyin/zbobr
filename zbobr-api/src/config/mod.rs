impl ZbobrDispatcherConfig {
    /// Load configuration from environment variables only (backward compat).
    pub fn from_env() -> anyhow::Result<Self> {
        let cwd = std::env::current_dir()
            .map_err(|e| anyhow::anyhow!("Cannot get current directory: {e}"))?;
        Ok(<Self as Config>::build(
            None,
            ZbobrDispatcherArgs::default(),
            &cwd,
        ))
    }

    /// Returns the configured timezone offset, or the system's local timezone if not set.
    pub fn fixed_offset(&self) -> chrono::FixedOffset {
        match &self.timezone {
            Some(tz) => **tz,
            None => *chrono::Local::now().offset(),
        }
    }

    /// Validate configuration consistency and resolve all secrets.
    pub fn validate(&mut self) -> anyhow::Result<()> {
        // Verify parent references are valid
        for (provider_name, provider) in &self.providers {
            if let Some(parent) = provider.parent.as_option()
                && !self.providers.contains_key(parent.as_str())
            {
                anyhow::bail!(
                    "Provider '{}' references unknown parent '{}'",
                    provider_name,
                    parent.as_str()
                );
            }
            if provider.executor.is_none() && provider.parent.is_none() {
                anyhow::bail!(
                    "Provider '{}' has neither 'executor' nor 'parent' — one is required",
                    provider_name
                );
            }
            if let Some(executor) = provider.executor.as_option() {
                let valid = [Executor::CLAUDE, Executor::COPILOT, Executor::MCP_TESTER];
                if !valid.contains(&executor.as_str()) {
                    anyhow::bail!(
                        "Provider '{}' has unknown executor '{}' — must be one of 'claude', 'copilot', 'mcp-tester'",
                        provider_name,
                        executor
                    );
                }
            }
        }
        // Verify tool entries reference existing providers
        for (tool_name, entries) in &self.tools {
            for entry in entries {
                if !self.providers.contains_key(entry.provider.as_str()) {
                    anyhow::bail!(
                        "Tool '{}' references unknown provider '{}'",
                        tool_name,
                        entry.provider
                    );
                }
            }
        }
        self.agent_github_token.resolve()?;
        // Resolve secrets in providers
        for provider in self.providers.values_mut() {
            if let TomlOption::Value(ref mut key) = provider.access_key {
                key.resolve()?;
            }
        }
        Ok(())
    }

    /// Validate that all tool-name references in role and stage definitions exist in `self.tools`.
    pub fn validate_workflow_refs(&self, workflow: &WorkflowConfig) -> anyhow::Result<()> {
        for (role_name, role_def) in workflow.roles.as_ref().into_iter().flat_map(|roles| {
            roles
                .iter()
                .filter_map(|(name, def)| def.as_option().map(|def| (name, def)))
        }) {
            let Some(tool) = role_def.tool.as_option() else {
                anyhow::bail!("Role '{}' has no tool defined", role_name);
            };
            if !self.tools.contains_key(tool.as_str()) {
                anyhow::bail!(
                    "Role '{}' references unknown tool '{}' (not in [tools])",
                    role_name,
                    tool
                );
            }
        }
        for (pname, pipeline) in workflow.pipelines.as_ref().into_iter().flat_map(|pipelines| {
            pipelines
                .iter()
                .filter_map(|(name, def)| def.as_option().map(|def| (name, def)))
        }) {
            for (sname, stage) in pipeline
                .stages
                .as_ref()
                .into_iter()
                .flat_map(|stages| stages.iter())
                .filter_map(|(sname, stage)| stage.as_option().map(|stage| (sname, stage)))
            {
                if let Some(tool) = stage.tool.as_option()
                    && !self.tools.contains_key(tool.as_str())
                {
                    anyhow::bail!(
                        "Stage '{}/{}' references unknown tool '{}' (not in [tools])",
                        pname,
                        sname,
                        tool
                    );
                }
            }
        }
        Ok(())
    }

    /// Determine the effective tool name for a stage.
    ///
    /// Precedence: stage.tool → role.tool
    pub fn resolve_tool(
        &self,
        stage_def: &StageDefinition,
        workflow: &WorkflowConfig,
    ) -> anyhow::Result<Tool> {
        match &stage_def.tool {
            TomlOption::Value(tool) => return Ok(tool.clone()),
            TomlOption::ExplicitNone => anyhow::bail!(
                "Tool explicitly cleared (nan) for stage with role {:?}",
                stage_def.role()
            ),
            TomlOption::Absent => {}
        }
        if let Some(role_name) = stage_def.role().map(|r| r.as_str())
            && let Some(role_def) = workflow.role_definition(role_name)
            && let Some(ref tool) = role_def.tool.as_option()
        {
            return Ok((*tool).clone());
        }
        anyhow::bail!(
            "No tool found for stage {:?} with role {:?}",
            stage_def,
            stage_def.role()
        );
    }

    /// Resolve all providers by flattening inheritance chains.
    ///
    /// Returns an `IndexMap` from provider to `ResolvedProvider`.
    pub fn resolve_providers(&self) -> anyhow::Result<IndexMap<Provider, ResolvedProvider>> {
        let mut resolved = IndexMap::new();
        for provider in self.providers.keys() {
            let rp = self.resolve_single_provider(provider.clone(), &mut Vec::new())?;
            resolved.insert(provider.clone(), rp);
        }
        Ok(resolved)
    }

    fn resolve_single_provider(
        &self,
        provider: Provider,
        visited: &mut Vec<Provider>,
    ) -> anyhow::Result<ResolvedProvider> {
        if visited.contains(&provider) {
            anyhow::bail!(
                "Circular parent reference detected in provider '{}'",
                provider.as_str()
            );
        }
        visited.push(provider.clone());

        let def = self
            .providers
            .get(&provider)
            .ok_or_else(|| anyhow::anyhow!("Provider '{}' not found", provider.as_str()))?;

        if let Some(ref parent_name) = def.parent.as_option() {
            let parent = self.resolve_single_provider((*parent_name).clone(), visited)?;
            let executor = match def.executor.clone() {
                TomlOption::Value(e) => e,
                TomlOption::Absent => parent.executor,
                TomlOption::ExplicitNone => anyhow::bail!(
                    "Provider '{}' explicitly clears executor (nan), but executor is required",
                    provider
                ),
            };
            let priority = match def.priority.clone() {
                TomlOption::Value(p) => p,
                TomlOption::Absent => parent.priority,
                TomlOption::ExplicitNone => 10,
            };
            let plan_mode = match def.plan_mode.clone() {
                TomlOption::Value(p) => p,
                TomlOption::Absent => parent.plan_mode,
                TomlOption::ExplicitNone => false,
            };
            let access_key = match def.access_key.clone() {
                TomlOption::Value(k) => Some(k),
                TomlOption::Absent => parent.access_key,
                TomlOption::ExplicitNone => None,
            };
            Ok(ResolvedProvider {
                provider: provider.clone(),
                executor,
                priority,
                plan_mode,
                access_key,
            })
        } else {
            let executor = def.executor.clone().into_option().ok_or_else(|| {
                anyhow::anyhow!("Provider '{}' has no executor and no parent", provider)
            })?;
            Ok(ResolvedProvider {
                provider: provider.clone(),
                executor,
                priority: def.priority.clone().into_option().unwrap_or(10),
                plan_mode: def.plan_mode.clone().into_option().unwrap_or(false),
                access_key: def.access_key.clone().into_option(),
            })
        }
    }
}

