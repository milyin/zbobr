use std::collections::HashMap;
use std::path::PathBuf;

use zbobr_utility::config_struct;

use crate::task::{Model, Tool};

/// Validate a single signal string: must be `go_X`, `call_X[,go_Y|return]`, or `return`.
fn validate_signal(
    pipeline_name: &str,
    stage_name: &str,
    field_name: &str,
    signal: &str,
    pipelines: &[&str],
    pipeline: &PipelineConfig,
) -> anyhow::Result<()> {
    if let Some(target) = signal.strip_prefix("go_") {
        if pipeline.stage(target).is_none() {
            anyhow::bail!(
                "Stage '{}/{}' {} 'go_{}' references unknown stage '{}' in pipeline '{}'",
                pipeline_name, stage_name, field_name, target, target, pipeline_name
            );
        }
    } else if signal.starts_with("call_") {
        let call_part = signal.split(',').next().unwrap();
        let target_pipeline = call_part.strip_prefix("call_").unwrap();
        if !pipelines.contains(&target_pipeline) {
            anyhow::bail!(
                "Stage '{}/{}' {} '{}' references unknown pipeline '{}'",
                pipeline_name, stage_name, field_name, signal, target_pipeline
            );
        }
        if let Some(after_return) = signal.split_once(',').map(|(_, s)| s.trim()) {
            if let Some(target_stage) = after_return.strip_prefix("go_") {
                if pipeline.stage(target_stage).is_none() {
                    anyhow::bail!(
                        "Stage '{}/{}' {} '{}' after-return references unknown stage '{}' in pipeline '{}'",
                        pipeline_name, stage_name, field_name, signal, target_stage, pipeline_name
                    );
                }
            } else if after_return != "return" {
                anyhow::bail!(
                    "Stage '{}/{}' {} '{}' after-return signal '{}' is invalid (expected go_X or return)",
                    pipeline_name, stage_name, field_name, signal, after_return
                );
            }
        }
    } else if signal != "return" {
        anyhow::bail!(
            "Stage '{}/{}' {} '{}' is invalid (expected go_X, call_X, or return)",
            pipeline_name, stage_name, field_name, signal
        );
    }
    Ok(())
}

/// Auto-generated by #[config_struct] for every config struct.
pub trait Config: Sized {
    type Toml: Default + for<'de> serde::Deserialize<'de>;
    type Args: clap::Args + zbobr_utility::PrefixedArgs + Default + Clone;
    fn build(toml: Option<Self::Toml>, args: Self::Args, config_dir: &std::path::Path) -> Self;
}

/// Definition of a role: which MCP tools it can access, and an optional prompt file.
#[derive(Clone, Debug, serde::Deserialize, serde::Serialize)]
pub struct RoleDefinition {
    pub tools: Vec<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub prompt: Option<PathBuf>,
}

/// A single stage in the configurable pipeline.
///
/// The stage's name and pipeline are derived from its structural position
/// (key in the stages HashMap and key in the pipelines HashMap).
#[derive(Clone, Debug, serde::Deserialize, serde::Serialize)]
pub struct StageDefinition {
    pub role: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub model: Option<Model>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tool: Option<Tool>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub main_prompt: Option<PathBuf>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub additional_prompts: Vec<PathBuf>,
    /// Signal to emit when the agent calls `report_success`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub on_success: Option<String>,
    /// Signal to emit when the agent calls `report_failure`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub on_failure: Option<String>,
}

impl Default for StageDefinition {
    fn default() -> Self {
        Self {
            role: String::new(),
            model: None,
            tool: None,
            main_prompt: None,
            additional_prompts: vec![],
            on_success: None,
            on_failure: None,
        }
    }
}

/// Per-pipeline configuration: a named directed graph of stages.
#[derive(Clone, Debug, Default, serde::Deserialize, serde::Serialize)]
pub struct PipelineConfig {
    /// Name of the start stage. Can be omitted when the pipeline has exactly one stage.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub start: Option<String>,
    #[serde(default)]
    pub stages: HashMap<String, StageDefinition>,
    /// Max retries for this pipeline's worktree handler before pausing.
    #[serde(default = "default_max_retries", skip_serializing_if = "is_default_max_retries")]
    pub max_retries: u32,
}

fn default_max_retries() -> u32 {
    5
}

fn is_default_max_retries(v: &u32) -> bool {
    *v == default_max_retries()
}

impl PipelineConfig {
    /// Look up a stage by name.
    pub fn stage(&self, name: &str) -> Option<&StageDefinition> {
        self.stages.get(name)
    }

    /// Get the start stage for this pipeline.
    ///
    /// Uses the explicit `start` field if set, otherwise falls back to the
    /// single stage when the pipeline contains exactly one.
    pub fn start_stage(&self) -> Option<(&str, &StageDefinition)> {
        if let Some(ref start) = self.start {
            self.stages.get(start.as_str()).map(|s| (start.as_str(), s))
        } else if self.stages.len() == 1 {
            self.stages.iter().next().map(|(n, s)| (n.as_str(), s))
        } else {
            None
        }
    }

    /// Validate pipeline configuration.
    pub fn validate(&self, pipeline_name: &str) -> anyhow::Result<()> {
        if let Some(ref start) = self.start {
            if !self.stages.contains_key(start) {
                anyhow::bail!(
                    "Pipeline '{}' start = '{}' references unknown stage",
                    pipeline_name, start
                );
            }
        } else if self.stages.len() != 1 {
            anyhow::bail!(
                "Pipeline '{}' has {} stages but no 'start' field (required when stages > 1)",
                pipeline_name, self.stages.len()
            );
        }
        Ok(())
    }
}

/// Top-level workflow configuration: a container of named pipelines and shared roles.
///
/// Replaces the old `PipelineConfig` at the top level. Defined manually
/// (not via `#[config_struct]`) because `#[serde(flatten)]` on pipelines
/// is incompatible with `deny_unknown_fields`.
#[derive(Clone, Debug, Default, serde::Deserialize, serde::Serialize)]
pub struct WorkflowConfig {
    #[serde(default)]
    pub roles: HashMap<String, RoleDefinition>,
    #[serde(default)]
    pub pipelines: HashMap<String, PipelineConfig>,
}

/// TOML representation of WorkflowConfig (all fields optional).
#[derive(Clone, Debug, Default, serde::Deserialize, serde::Serialize)]
pub struct WorkflowToml {
    #[serde(default)]
    pub roles: Option<HashMap<String, RoleDefinition>>,
    #[serde(default)]
    pub pipelines: Option<HashMap<String, PipelineConfig>>,
}

/// CLI arguments for WorkflowConfig (empty — no CLI-overridable fields).
#[derive(Clone, Debug, Default)]
pub struct WorkflowArgs;

impl clap::Args for WorkflowArgs {
    fn augment_args(cmd: clap::Command) -> clap::Command {
        cmd
    }
    fn augment_args_for_update(cmd: clap::Command) -> clap::Command {
        cmd
    }
}

impl clap::FromArgMatches for WorkflowArgs {
    fn from_arg_matches(_matches: &clap::ArgMatches) -> Result<Self, clap::Error> {
        Ok(WorkflowArgs)
    }
    fn update_from_arg_matches(&mut self, _matches: &clap::ArgMatches) -> Result<(), clap::Error> {
        Ok(())
    }
}

impl zbobr_utility::PrefixedArgs for WorkflowArgs {
    fn augment_args_prefixed(cmd: clap::Command, _prefix: &str) -> clap::Command {
        cmd
    }
    fn from_matches_prefixed(
        _matches: &clap::ArgMatches,
        _prefix: &str,
    ) -> Result<Self, clap::Error> {
        Ok(WorkflowArgs)
    }
}

impl WorkflowArgs {
    pub fn has_overrides(&self) -> bool {
        false
    }
}

impl WorkflowToml {
    pub fn merge_with_args(self, _args: WorkflowArgs) -> Self {
        self
    }

    pub fn try_into_config(self) -> anyhow::Result<WorkflowConfig> {
        Ok(WorkflowConfig {
            roles: self.roles.unwrap_or_default(),
            pipelines: self.pipelines.unwrap_or_default(),
        })
    }
}

impl Config for WorkflowConfig {
    type Toml = WorkflowToml;
    type Args = WorkflowArgs;

    fn build(toml: Option<Self::Toml>, _args: Self::Args, _config_dir: &std::path::Path) -> Self {
        match toml {
            Some(t) => WorkflowConfig {
                roles: t.roles.unwrap_or_default(),
                pipelines: t.pipelines.unwrap_or_default(),
            },
            None => WorkflowConfig::default(),
        }
    }
}

impl WorkflowConfig {
    /// Required pipeline: main task processing.
    pub const MAIN_PIPELINE: &'static str = "main";
    /// Required pipeline: initialization when worktree identity is undefined.
    pub const INIT_PIPELINE: &'static str = "init";
    /// Required pipeline: merge conflict resolution.
    pub const MERGE_PIPELINE: &'static str = "merge";

    /// Look up a pipeline by name.
    pub fn pipeline(&self, name: &str) -> Option<&PipelineConfig> {
        self.pipelines.get(name)
    }

    /// Look up a stage in a specific pipeline.
    pub fn stage(&self, pipeline: &str, stage: &str) -> Option<&StageDefinition> {
        self.pipelines.get(pipeline)?.stage(stage)
    }

    /// Get the start stage for a pipeline.
    pub fn start_stage_for_pipeline(&self, pipeline: &str) -> Option<(&str, &StageDefinition)> {
        self.pipelines.get(pipeline)?.start_stage()
    }

    /// The default pipeline name.
    pub fn default_pipeline(&self) -> &str {
        Self::MAIN_PIPELINE
    }

    /// All pipeline names.
    pub fn pipeline_names(&self) -> Vec<&str> {
        let mut names: Vec<&str> = self.pipelines.keys().map(|s| s.as_str()).collect();
        names.sort();
        names
    }

    /// Find the first stage with a given role (across all pipelines, preferring default pipeline).
    pub fn find_stage_by_role(&self, role: &str) -> Option<(&str, &str, &StageDefinition)> {
        let default = self.default_pipeline();
        if let Some(pipeline) = self.pipelines.get(default) {
            if let Some((name, stage)) = pipeline.stages.iter().find(|(_, s)| s.role == role) {
                return Some((default, name.as_str(), stage));
            }
        }
        for (pname, pipeline) in &self.pipelines {
            if let Some((sname, stage)) = pipeline.stages.iter().find(|(_, s)| s.role == role) {
                return Some((pname.as_str(), sname.as_str(), stage));
            }
        }
        None
    }

    /// Look up a role definition by name.
    pub fn role_definition(&self, role: &str) -> Option<&RoleDefinition> {
        self.roles.get(role)
    }

    /// Iterate over all stages as `(pipeline_name, stage_name, &StageDefinition)` tuples.
    pub fn all_stages(&self) -> Vec<(&str, &str, &StageDefinition)> {
        let mut result = Vec::new();
        for (pname, pipeline) in &self.pipelines {
            for (sname, stage) in &pipeline.stages {
                result.push((pname.as_str(), sname.as_str(), stage));
            }
        }
        result
    }

    /// Validate the entire workflow configuration.
    pub fn validate(&self) -> anyhow::Result<()> {
        // Required pipelines must exist
        for required in [Self::MAIN_PIPELINE, Self::INIT_PIPELINE, Self::MERGE_PIPELINE] {
            if !self.pipelines.contains_key(required) {
                anyhow::bail!(
                    "Required pipeline '{}' is missing from [workflow.pipelines]",
                    required
                );
            }
        }

        let pipeline_names = self.pipeline_names();

        // Each pipeline must have a valid start stage
        for &pname in &pipeline_names {
            let pipeline = self.pipelines.get(pname).unwrap();
            pipeline.validate(pname)?;
        }

        // Validate on_success / on_failure signal targets
        for &pname in &pipeline_names {
            let pipeline = self.pipelines.get(pname).unwrap();
            for (sname, stage) in &pipeline.stages {
                if let Some(ref signal) = stage.on_success {
                    validate_signal(pname, sname, "on_success", signal, &pipeline_names, pipeline)?;
                }
                if let Some(ref signal) = stage.on_failure {
                    validate_signal(pname, sname, "on_failure", signal, &pipeline_names, pipeline)?;
                }
            }
        }

        // Every stage's role must exist in the roles map (if roles are configured)
        if !self.roles.is_empty() {
            for (pname, pipeline) in &self.pipelines {
                for (sname, stage) in &pipeline.stages {
                    if !self.roles.contains_key(&stage.role) {
                        anyhow::bail!(
                            "Stage '{}/{}' references unknown role '{}' (not in [workflow.roles])",
                            pname, sname, stage.role
                        );
                    }
                }
            }
        }

        Ok(())
    }
}

/// Configuration for the zbobr dispatcher.
#[derive(Clone)]
#[config_struct]
pub struct ZbobrDispatcherConfig {
    /// Workspaces directory; each task gets a separate subdirectory.
    #[config(path)]
    pub workspaces: std::path::PathBuf,
    /// Base port for the MCP server; zbobr scans upward from this port to find
    /// an available one.
    #[arg(default_value = "3000")]
    pub base_port: u16,
    /// Read-only GitHub token passed as GH_TOKEN/GITHUB_TOKEN to agent processes.
    /// This is a security boundary: it limits what agents can do on GitHub — agents must
    /// not have write access so that erroneous or misbehaving agents cannot modify remote
    /// repositories. Use a fine-grained token with read-only scopes (or no scopes at all
    /// for fully offline/mcp-tester runs). Defaults to "not-configured" when omitted.
    pub agent_github_token: String,
    /// CLI tool to use as a global default. Individual stages may override this.
    pub tool: Tool,
    /// Global AI model to use when a stage does not specify an override.
    pub model: Model,
    /// Prefix for work branches (default: "zbobr_fix").
    pub work_branch_prefix: String,
    /// Default destination repository pre-populated into task parameters before the
    /// preparator agent runs (e.g. "owner/repo" or a full git URL). The preparator
    /// may still override this value.
    pub default_destination_repository: Option<String>,
    /// Default destination branch pre-populated into task parameters before the
    /// preparator agent runs (e.g. "main"). The preparator may still override this.
    pub default_destination_branch: Option<String>,
}

impl Default for ZbobrDispatcherConfig {
    fn default() -> Self {
        Self {
            workspaces: std::path::PathBuf::from("./workspaces"),
            base_port: 3000,
            agent_github_token: "not-configured".to_string(),
            tool: Tool::default(),
            model: Model::default(),
            work_branch_prefix: "zbobr_fix".to_string(),
            default_destination_repository: None,
            default_destination_branch: None,
        }
    }
}

impl ZbobrDispatcherConfig {
    /// Load configuration from environment variables only (backward compat).
    pub fn from_env() -> anyhow::Result<Self> {
        let cwd = std::env::current_dir()
            .map_err(|e| anyhow::anyhow!("Cannot get current directory: {e}"))?;
        Ok(<Self as Config>::build(
            None,
            ZbobrDispatcherArgs::default(),
            &cwd,
        ))
    }

    /// Validate that global tool/model are compatible.
    pub fn validate(&self) -> anyhow::Result<()> {
        if self.model.model_name_for_tool(self.tool).is_none() {
            anyhow::bail!(
                "Global model {:?} is not supported by global tool {:?}",
                self.model,
                self.tool
            );
        }
        Ok(())
    }

    /// Determine which tool to use for a stage, falling back to global default.
    pub fn tool_for_stage(&self, stage_def: &StageDefinition) -> Tool {
        stage_def.tool.unwrap_or(self.tool)
    }

    /// Determine which model to use for a stage, falling back to global default.
    pub fn model_for_stage(&self, stage_def: &StageDefinition) -> Model {
        stage_def.model.clone().unwrap_or(self.model.clone())
    }
}
